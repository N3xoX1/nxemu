#pragma once
#include <cstdint>
#include <filesystem>
#include <initializer_list>
#include <string>

namespace Rml
{
class Context;
class ElementDocument;
} // namespace Rml

// The texts of the interface are written in English where they are used, and
// shown in the interface's language. lang/nxemu.pot lists them all: it is
// made from the sources by lang/extract_strings.py, which finds the texts
// given to the functions below and those of the documents. A translation is
// a copy of that list, with each text in its language.

// The text in the interface's language; the text itself when the language
// has none for it.
std::string Tr(const char * text);
// The text in capitals, accented letters included: RmlUi's text-transform
// only knows the unaccented ones. A document asks for it with the attribute
// "data-upper", which holds for all the text of the element.
std::string TrUpper(const std::string & text);
// The same, with %1, %2... replaced by the values, in the order the language
// wants them.
std::string Tr(const char * text, std::initializer_list<std::string> values);
// The text for a count: one of the forms the language has for it, with %n
// replaced by the count. English has two, for one and for any other count.
std::string TrCount(const char * one, const char * other, uint64_t count);
// Marks a text kept in a table for Tr() to translate when it is shown.
constexpr const char * TrMark(const char * text)
{
    return text;
}

namespace Translation
{
struct LanguageInfo
{
    const char * code;
    const char * name; // In the language itself, so it can always be recognised.
};
inline constexpr LanguageInfo Languages[] = {
    {"de", "Deutsch"}, {"en", "English"}, {"es", "Español"}, {"fr", "Français"}, {"it", "Italiano"},
    {"nl", "Nederlands"}, {"pt", "Português"}, {"ru", "Русский"}, {"ja", "日本語"}, {"ko", "한국어"}, {"zh", "中文"},
};
bool IsSupportedLanguage(const std::string & code);
// Regional console variants share one interface catalogue.
const char * LanguageOfConsole(int32_t language);
// An empty or unsupported override follows the console language.
std::string ResolveLanguage(int32_t consoleLanguage, const std::string & overrideCode);
bool UseLanguage(const std::string & code, const std::filesystem::path & directory, const std::filesystem::path & fallbackDirectory);

// Reads the texts of a language from a gettext catalogue, a .po file. False
// when it cannot be read: the interface stays as it was.
bool Load(const std::filesystem::path & file);
// Back to English.
void Clear();

// Loads a document with its texts in the interface's language: its text
// nodes, and the explanations and hints its elements have as attributes.
// What is written into it afterwards has to be in that language already.
Rml::ElementDocument * LoadDocument(Rml::Context & context, const std::filesystem::path & file);
// Updates only the original document text. Text added by the views is
// regenerated by those views, so game names and user data stay untouched.
void RefreshDocument(Rml::ElementDocument & document);
} // namespace Translation
